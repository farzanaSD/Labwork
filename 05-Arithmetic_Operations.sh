#!/bin/bash

# Variable Declaration and Arithmetic Operations in Bash

# Declaring a variable
var=5

# Printing the value of the variable
echo "Value of var = $var"

# Declaring two variables
a=3
b=2

# Addition
echo "Addition = $((a+b))"

# Subtraction
echo "Subtraction = $((a-b))"

# Multiplication
echo "Multiplication = $((a*b))"

# Division
echo "Division = $((a/b))"
